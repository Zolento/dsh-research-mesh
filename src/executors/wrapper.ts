/**
 * Conda invocation and the remote job wrapper.
 *
 * The wrapper is generated from a validated manifest. Every interpolated value
 * is single-quoted; no manifest string is concatenated as shell syntax. The
 * wrapper runs the conda command, writes a durable state file, stages artifacts
 * in a temporary directory and produces a SHA-256 artifact manifest only after
 * the process succeeds.
 */

import { MeshError } from '../errors.ts';
import { quoteArgv, shellQuote } from '../util/shell.ts';
import { requireRelativePath } from '../util/fs-safe.ts';
import type { CondaConfig } from '../config/types.ts';
import type { JobManifest } from './manifest.ts';

/**
 * Build the canonical Conda launch argv.
 * @param conda - conda executable policy.
 * @param environment - environment name.
 * @param entrypoint - program or relative script.
 * @param argv - program arguments.
 * @returns argv array with no shell layer.
 */
export function buildCondaArgv(
  conda: CondaConfig,
  environment: string,
  entrypoint: string,
  argv: readonly string[],
): readonly string[] {
  return [conda.executable, 'run', '-n', environment, '--no-capture-output', entrypoint, ...argv];
}

/** Inputs for wrapper generation. */
export interface WrapperInput {
  readonly manifest: JobManifest;
  readonly jobDir: string;
  readonly conda: CondaConfig;
  readonly gpuId: number | null;
}

export const ARTIFACT_MANIFEST_PY = String.raw`
import hashlib
import json
import os
import sys

root, job_id, attempt_id, manifest_sha = sys.argv[1:5]
files = []
total = 0
for base, _dirs, names in os.walk(root):
    for name in names:
        path = os.path.join(base, name)
        rel = os.path.relpath(path, root).replace(os.sep, "/")
        if rel == "artifact-manifest.json":
            continue
        st = os.lstat(path)
        if os.path.islink(path) or not os.path.isfile(path):
            raise SystemExit("artifact is not a regular file: " + rel)
        digest = hashlib.sha256()
        with open(path, "rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
        digest = digest.hexdigest()
        files.append({"path": rel, "sha256": digest, "size_bytes": st.st_size})
        total += st.st_size
files.sort(key=lambda item: item["path"])
doc = {
    "schema": "dsh-research-mesh/artifact-manifest@1",
    "job_id": job_id,
    "attempt_id": attempt_id,
    "manifest_sha256": manifest_sha,
    "status": "complete",
    "created_at": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "files": files,
    "total_bytes": total,
}
tmp = os.path.join(root, ".artifact-manifest.json.tmp")
with open(tmp, "w", encoding="utf-8") as handle:
    handle.write(json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
os.replace(tmp, os.path.join(root, "artifact-manifest.json"))
`;

/**
 * Generate the deterministic remote wrapper for one manifest.
 * @param input - manifest, absolute job directory, conda policy and GPU.
 * @returns a POSIX shell script.
 */
export function buildWrapperScript(input: WrapperInput): string {
  const { manifest, jobDir, conda, gpuId } = input;
  const destination = requireRelativePath(manifest.artifacts.destination, 'artifacts.destination');
  const workingDirectory = manifest.execution.working_directory === '.'
    ? ''
    : requireRelativePath(manifest.execution.working_directory, 'working_directory');
  const sourceDir = workingDirectory === '' ? `${jobDir}/source` : `${jobDir}/source/${workingDirectory}`;
  const condaArgs = [
    conda.executable,
    'run',
    '-n',
    manifest.execution.conda_environment,
    '--no-capture-output',
    manifest.execution.entrypoint,
    ...manifest.execution.argv,
  ];
  const exportLines = Object.entries(manifest.environment ?? {})
    .map(([key, value]) => `export ${key}=${shellQuote(value)}`)
    .join('\n');
  return `#!/usr/bin/env bash
# Generated by dsh-research-mesh. Do not edit the running copy.
set -uo pipefail

JOB_DIR=${shellQuote(jobDir)}
JOB_ID=${shellQuote(manifest.job_id)}
ATTEMPT_ID=${shellQuote(manifest.attempt_id)}
MANIFEST_SHA=${shellQuote(manifest.manifest_sha256 ?? '')}
SOURCE_DIR=${shellQuote(sourceDir)}
TMP_DIR="$JOB_DIR/artifacts.tmp"
FINAL_DIR="$JOB_DIR/${destination}"
STATE_DIR="$JOB_DIR/state"
LOG_OUT="$JOB_DIR/logs/stdout.log"
LOG_ERR="$JOB_DIR/logs/stderr.log"
STATE_FILE="$STATE_DIR/job-state.json"
STATE_TMP="$STATE_DIR/.job-state.json.tmp"
STARTED_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

mkdir -p "$STATE_DIR" "$JOB_DIR/logs" "$TMP_DIR" "$(dirname "$FINAL_DIR")"

write_state() {
  status="$1"
  code="$2"
  message="$3"
  finished="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  if [ -z "$message" ]; then
    printf '{"schema":"dsh-research-mesh/remote-state@1","job_id":"%s","attempt_id":"%s","manifest_sha256":"%s","status":"%s","exit_code":%s,"started_at":"%s","finished_at":"%s"}\\n' \\
      "$JOB_ID" "$ATTEMPT_ID" "$MANIFEST_SHA" "$status" "$code" "$STARTED_AT" "$finished" > "$STATE_TMP"
  else
    printf '{"schema":"dsh-research-mesh/remote-state@1","job_id":"%s","attempt_id":"%s","manifest_sha256":"%s","status":"%s","exit_code":%s,"started_at":"%s","finished_at":"%s","error":"%s"}\\n' \\
      "$JOB_ID" "$ATTEMPT_ID" "$MANIFEST_SHA" "$status" "$code" "$STARTED_AT" "$finished" "$message" > "$STATE_TMP"
  fi
  mv "$STATE_TMP" "$STATE_FILE"
}

write_state running null ""
echo "[dsh-research-mesh] job $JOB_ID attempt $ATTEMPT_ID started $STARTED_AT" >> "$LOG_OUT"
${exportLines}
export MESH_JOB_ID="$JOB_ID"
export MESH_ATTEMPT_ID="$ATTEMPT_ID"
export MESH_JOB_DIR="$JOB_DIR"
export MESH_ARTIFACT_DIR="$TMP_DIR"
${gpuId === null ? '# no GPU requested' : `export CUDA_VISIBLE_DEVICES=${shellQuote(String(gpuId))}`}

if ! cd "$SOURCE_DIR"; then
  write_state failed 127 "working directory is missing"
  exit 0
fi

${quoteArgv(condaArgs)} >> "$LOG_OUT" 2>> "$LOG_ERR"
rc=$?
if [ "$rc" -ne 0 ]; then
  echo "[dsh-research-mesh] entrypoint exited $rc" >> "$LOG_ERR"
  write_state failed "$rc" "entrypoint exited nonzero"
  exit 0
fi

if [ -e "$FINAL_DIR" ]; then
  write_state failed 73 "artifact destination already exists"
  exit 0
fi
mkdir -p "$(dirname "$FINAL_DIR")"
mv "$TMP_DIR" "$FINAL_DIR"
if ! ${shellQuote(conda.executable)} run -n ${shellQuote(manifest.execution.conda_environment)} --no-capture-output python3 "$JOB_DIR/artifact_manifest.py" "$FINAL_DIR" "$JOB_ID" "$ATTEMPT_ID" "$MANIFEST_SHA" >> "$LOG_OUT" 2>> "$LOG_ERR"
then
  write_state failed 74 "artifact manifest generation failed"
  exit 0
fi
write_state succeeded 0 ""
exit 0
`;
}

/**
 * Write the artifact-manifest helper used by the wrapper.
 * @param jobDir - absolute job directory.
 * @returns absolute helper path.
 */
export function artifactManifestScriptPath(jobDir: string): string {
  return `${jobDir}/artifact_manifest.py`;
}

/**
 * Build the fixed wrapper path inside a job directory.
 * @param jobDir - absolute job directory.
 * @returns absolute wrapper path.
 */
export function wrapperPath(jobDir: string): string {
  return `${jobDir}/run.sh`;
}

/**
 * Build the fixed state path inside a job directory.
 * @param jobDir - absolute job directory.
 * @returns absolute state path.
 */
export function statePath(jobDir: string): string {
  return `${jobDir}/state/job-state.json`;
}

/**
 * Build the fixed artifact-manifest path inside a job directory.
 * @param jobDir - absolute job directory.
 * @param destination - manifest artifact destination.
 * @returns absolute artifact-manifest path.
 */
export function artifactManifestPath(jobDir: string, destination: string): string {
  return `${jobDir}/${requireRelativePath(destination, 'artifacts.destination')}/artifact-manifest.json`;
}

/**
 * Validate that a wrapper command target is a known conda executable.
 * @param conda - conda policy.
 * @returns the executable path/name.
 */
export function condaExecutable(conda: CondaConfig): string {
  if (conda.executable.includes('\0') || conda.executable.includes('\n')) {
    throw new MeshError('CONFIG_INVALID', 'conda executable contains an invalid character');
  }
  return conda.executable;
}
